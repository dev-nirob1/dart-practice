void main() {
  var marks = 81;
  switch (marks) {
    case 80:
      print('Result is A+');
      break;
    case 70:
      print('Result is A-');
      break;
    case 60:
      print('Result is B');
      break;
    default:
      print('Result not found');
      break;
  }
  print('switch case');
}
